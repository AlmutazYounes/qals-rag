def compute_gini(frequencies: List[int]) -> float:
    """Computes Gini coefficient of retrieval concentration (measuring hub dominance)."""
    arr = np.array(frequencies, dtype=np.float64)
    if np.sum(arr) == 0:
        return 0.0
    arr = np.sort(arr)
    n = len(arr)
    index = np.arange(1, n + 1)
    return float((np.sum((2 * index - n - 1) * arr)) / (n * np.sum(arr)))


def run_benchmark():
    corpus, queries = generate_synthetic_evaluation_corpus()
    embedder = HashFeatureEmbedder(dim=256, anisotropy_strength=0.08)

    # 1. Baseline: Flat Dense Retriever (500-char chunks, k=5)
    flat_dense = FlatDenseRetriever(embedder=embedder, chunk_size=350, overlap=40)
    flat_dense.index_documents(corpus)

    # 2. Baseline: BM25 Lexical
    bm25 = BM25Retriever(chunk_size=350)
    bm25.index_documents(corpus)

    # 3. TopoRAG (Proposed)
    toporag = TopoRAGRetriever(embedder=embedder)
    toporag.index_documents(corpus)

    systems = {
        "BM25": lambda q: [r["doc_id"] for r in bm25.retrieve(q, k=5)],
        "Flat-Dense (Fixed k=5)": lambda q: [r["doc_id"] for r in flat_dense.retrieve(q, k=5)],
        "TopoRAG (Proposed)": lambda q: [r["doc_id"] for r in toporag.retrieve(q)["results"]],
    }

    results = {}

    for sys_name, retrieve_fn in systems.items():
        hit_count = 0
        mrr_total = 0.0
        ndcg_total = 0.0
        total_retrieved_items = 0
        doc_retrieval_freqs = {d["id"]: 0 for d in corpus}
        latencies = []

        for q_obj in queries:
            query_str = q_obj["query"]
            gold = set(q_obj["gold_doc_ids"])

            t0 = time.perf_counter()
            retrieved_doc_ids = retrieve_fn(query_str)
            lat = (time.perf_counter() - t0) * 1000
            latencies.append(lat)

            total_retrieved_items += len(retrieved_doc_ids)

            # Record frequency
            for d in retrieved_doc_ids:
                if d in doc_retrieval_freqs:
                    doc_retrieval_freqs[d] += 1

            # Hit Rate
            hits = [1 if d in gold else 0 for d in retrieved_doc_ids]
            if any(hits):
                hit_count += 1

            # MRR
            rr = 0.0
            for rank, hit in enumerate(hits, start=1):
                if hit:
                    rr = 1.0 / rank
                    break
            mrr_total += rr

            # NDCG
            dcg = sum((hit / np.log2(rank + 1)) for rank, hit in enumerate(hits, start=1))
            ideal_hits = sorted(hits, reverse=True)
            idcg = sum((h / np.log2(rank + 1)) for rank, h in enumerate(ideal_hits, start=1))
            ndcg_total += (dcg / idcg) if idcg > 0 else 0.0

        n_q = len(queries)
        gini = compute_gini(list(doc_retrieval_freqs.values()))

        results[sys_name] = {
            "Hit Rate": round(hit_count / n_q, 4),
            "MRR": round(mrr_total / n_q, 4),
            "NDCG": round(ndcg_total / n_q, 4),
            "Avg Items Retrieved": round(total_retrieved_items / n_q, 2),
            "Hub Concentration (Gini)": round(gini, 4),
            "Avg Latency (ms)": round(float(np.mean(latencies)), 2),
        }

    return results, corpus, queries


if __name__ == "__main__":
    benchmark_results, _, _ = run_benchmark()
